#include <aglink_log.h>

static int aglink_debug_level = 2;
static int log_state;

int aglink_set_debug_level(int level)
{
    aglink_debug_level = level;
    return log_set_debug_level((log_level_t)level);
}

int aglink_set_debug_file_path(char *file_path)
{
	log_set_debug_type(LOG_BACKEND_FILE_SYNC);
	if (log_state == 1)
		return log_reset_path(file_path);
	log_state = 1;
	return log_start(file_path, "/tmp/aglink_io");
}

int aglink_stop_debug_file_log(void)
{
	log_set_debug_type(LOG_BACKEND_STDOUT_SYNC);
	if (log_state) {
		log_state = 0;
		return log_stop();
	}
	return 0;
}
